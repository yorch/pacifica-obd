"""Example seed->key provider for `pacifica-obd security --provider`.

This file is an **example**, not a real algorithm.  The constants below are
invented; nothing here unlocks any vehicle.  It exists to show the interface
that ``pacifica_obd.seedkey.load_provider`` expects, so you can drop in your
own provider (for instance one generated by ``tools/extract_seedkey.py`` from
your own AlfaOBD installation).

Interface
---------
``key_for(seed, **ctx) -> int``
    ``seed`` is passed as an ``int`` by ``pacifica_obd.uds.security_access``
    (it does ``int(seed_hex, 16)``), most often a 4-byte value such as
    ``0x12345678``.  Return the key as an ``int``, zero-padded to the key
    length the module expects (4 bytes => 8 hex digits).

Optional extras that the loader ignores but humans appreciate::

    NAME      = "example/not-a-real-algorithm"
    key_bytes(seed, **ctx) -> bytes     # same value, as bytes
    LEVELS    = (1, 5)                  # security levels this provider covers

Returning ``None`` means "I cannot compute a key for this seed", which the
tool reports as *no_key_provider* rather than sending a wrong key.

Licence: MIT.
"""

from __future__ import annotations

NAME = "example/not-a-real-algorithm"
LEVELS = (1, 5)

# Invented constants.  A real provider reads its constants from the vendor
# material you supply; see tools/extract_seedkey.py.
_MASK = 0xFFFFFFFF
_ODD = 0x9E3779B1
_EVEN = 0x85EBCA6B


def _rotl32(value: int, bits: int) -> int:
    value &= _MASK
    return ((value << bits) | (value >> (32 - bits))) & _MASK


def key_for(seed: int, **ctx) -> int:
    """Return the (fake) 4-byte key for ``seed``.

    ``ctx`` may carry whatever the caller knows: ``level``, ``device_id``,
    ``ecu``, ``variant`` ...  A multi-ECU provider switches on it here.
    """
    seed &= _MASK
    mixed = _rotl32(seed ^ _ODD, 11) ^ _EVEN
    mixed = (mixed + seed) & _MASK

    level = int(ctx.get("level", 1) or 1)
    if level not in LEVELS:
        return None

    return mixed & _MASK


def key_bytes(seed, **ctx) -> bytes:
    """Same value as :func:`key_for`, as the 4 bytes sent in service 0x27."""
    value = key_for(seed, **ctx)
    if value is None:
        return b""
    return value.to_bytes(4, "big")


if __name__ == "__main__":  # a five-second sanity check
    for sample in (0x12345678, 0x00000000, 0xDEADBEEF):
        print(f"{sample:08X} -> {key_bytes(sample).hex().upper()}")
