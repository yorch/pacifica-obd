"""Report building, storage registry, and the print-ready review template.

Three jobs live here (all read-only, all dependency-free):

* :func:`build_web_dump` — assemble the same dump dict shape the CLI writes, but
  from the web worker's own connections (a generic python-OBD pass plus a UDS
  pass). Keeping the shape identical means a report generated in the browser is
  interchangeable with one generated by ``pacifica-obd dump``.
* :class:`ReportRegistry` — an in-process registry of generated reports and the
  files written under the data dir. Nothing is written outside that dir.
* :func:`render_review_report` — the "review report": a self-contained, JS-free,
  print-first HTML document (the richer template; the built-in
  :func:`pacifica_obd.report.dump_to_html` remains available as the raw report).
"""

from __future__ import annotations

import html
import json
import threading
import uuid
import zipfile
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path

from pacifica_obd import report as report_mod
from pacifica_obd.profiles import year_from_vin
from pacifica_obd.store import data_dir
from pacifica_obd.web import service
from pacifica_obd.web.errors import ApiError, validation

DEFAULT_LIVE_PIDS = ["RPM", "SPEED", "COOLANT_TEMP", "ENGINE_LOAD", "CONTROL_MODULE_VOLTAGE"]


def _stamp() -> str:
    return datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")


# --------------------------------------------------------------------------- #
# building a dump
# --------------------------------------------------------------------------- #
def _blank_dump() -> dict:
    return {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "tool": {"name": "pacifica-obd-web", "version": _tool_version()},
        "adapter": {}, "vehicle": {},
        "generic": {"dtcs": {"stored": [], "pending": [], "permanent": []},
                    "readiness": {}, "live": {}, "supported_pids": 0},
        "modules": [], "readings": [],
        "totals": {"modules": 0, "dtcs": 0, "readings": 0},
        "aborted": None,
    }


def _tool_version() -> str:
    try:
        from importlib.metadata import version

        return version("pacifica-obd")
    except Exception:  # noqa: BLE001
        return "0.1.0"


def _live_text(value) -> str | None:
    """Render a ``{value, unit}`` reading the way the CLI prints it."""
    if value is None:
        return None
    if isinstance(value, dict) and "value" in value:
        unit = value.get("unit") or ""
        return f"{value['value']} {unit}".strip()
    return str(value)


def build_web_dump(ctx, *, bus: str = "both", start: int = 0x700, end: int = 0x7FF,
                   timeout_ms: int = 100, generic: bool = True, uds: bool = True,
                   vin: str | None = None) -> dict:
    """Collect everything readable into a CLI-shaped dump dict.

    Adapter failures are recorded as ``aborted`` (partial capture) rather than
    raised, matching the CLI's behaviour for ``dump``.
    """
    dump = _blank_dump()
    vin = service.jsonable(vin)
    buses = ["can-c", "can-ihs"] if bus == "both" else [bus]

    if generic:
        try:
            conn = ctx.obd()
            dump["adapter"] = service.obd_info(conn)
            gvn = dump["adapter"].get("vin")
            if isinstance(gvn, str) and gvn:
                vin = vin or gvn
            dump["generic"]["dtcs"] = service.obd_dtcs(conn)
            dump["generic"]["readiness"] = service.obd_readiness(conn)
            dump["generic"]["live"] = {
                row["name"]: _live_text(row["value"])
                for row in service.obd_live(conn, DEFAULT_LIVE_PIDS)
            }
            dump["generic"]["supported_pids"] = len([
                c for c in conn.supported_commands if service.is_read_only_command(c)
            ])
        except Exception as exc:  # noqa: BLE001 - partial is data too
            dump["aborted"] = f"generic pass failed: {exc}"
        finally:
            try:
                ctx.worker.backend.close()
            except Exception:  # noqa: BLE001
                pass

    if uds:
        try:
            adapter = ctx.uds()
            snapshot = service.capture_snapshot(
                adapter, buses=buses, start=start, end=end, timeout_ms=timeout_ms,
                cancel=ctx.cancel, progress=lambda event: ctx.progress(**event),
            )
            if snapshot.get("aborted"):
                dump["aborted"] = f"uds pass: {snapshot['aborted']}"
            vin = vin or snapshot.get("vin")
            dtc_by_rid = {row["request_id"]: row for row in snapshot["dtcs"]}
            identification: dict[str, dict] = {}
            for record in snapshot["readings"]:
                identification.setdefault(record["module"], {})[record["did"]] = {
                    "name": record.get("name"), "hex": record.get("hex"),
                    "ascii": record.get("ascii"), "status": record["status"],
                }
            for module in snapshot["modules"]:
                rid = module["request_id"]
                group = dtc_by_rid.get(rid, {})
                dump["modules"].append({
                    "bus": next((row["bus"] for row in snapshot["dtcs"]
                                 if row["request_id"] == rid), buses[0]),
                    "request_id": rid,
                    "response_id": module.get("response_id"),
                    "kind": module.get("kind"),
                    "dtcs": group.get("dtcs", []),
                    "identification": identification.get(rid, {}),
                })
                dump["readings"].append({
                    "bus": next((row["bus"] for row in snapshot["dtcs"]
                                 if row["request_id"] == rid), buses[0]),
                    "module": rid,
                    "identification": identification.get(rid, {}),
                })
        except Exception as exc:  # noqa: BLE001
            dump["aborted"] = f"uds pass failed: {exc}"
        finally:
            try:
                ctx.worker.backend.close()
            except Exception:  # noqa: BLE001
                pass

    year = year_from_vin(vin) if vin else None
    dump["vehicle"] = {
        "vin": vin, "year": year,
        "make": "Chrysler" if vin else None,
        "model": None, "profile_id": None, "powertrain": None,
    }
    generic_dtcs = dump["generic"].get("dtcs", {})
    dump["totals"] = {
        "modules": len(dump["modules"]),
        "dtcs": sum(len(generic_dtcs.get(key) or []) for key in ("stored", "pending", "permanent"))
        + sum(len(module["dtcs"]) for module in dump["modules"]),
        "readings": sum(len(module["identification"]) for module in dump["modules"]),
    }
    return dump


def dump_from_session(store, session_id: int) -> dict:
    """Rebuild a dump-shaped dict from stored rows (no adapter involved)."""
    rows = store._query("SELECT * FROM sessions WHERE id = ?", (session_id,))
    if not rows:
        raise ApiError("session_not_found", "not_found", f"no session {session_id}")
    session = rows[0]
    vin = session.get("vin")
    dump = _blank_dump()
    dump["tool"]["version"] = _tool_version()
    vehicle = {}
    if vin:
        vrows = store._query("SELECT * FROM vehicles WHERE vin = ?", (vin,))
        vehicle = vrows[0] if vrows else {}
    dump["vehicle"] = {
        "vin": vin, "year": vehicle.get("year") or (year_from_vin(vin) if vin else None),
        "make": vehicle.get("make"), "model": vehicle.get("model"),
        "profile_id": vehicle.get("profile_id"), "powertrain": vehicle.get("powertrain"),
    }
    dump["session"] = {"id": session_id, "command": session.get("command"),
                       "started_at": session.get("started_at"),
                       "ended_at": session.get("ended_at"), "status": session.get("status")}

    dtcs = store._query("SELECT * FROM dtcs WHERE session_id = ? ORDER BY module, code", (session_id,))
    module_rows = store._query("SELECT * FROM modules WHERE session_id = ?", (session_id,))
    readings = store._query("SELECT * FROM readings WHERE session_id = ? ORDER BY module, did", (session_id,))

    groups: dict[str, list[dict]] = {}
    for row in dtcs:
        groups.setdefault(row.get("module") or "?", []).append({
            "code": row.get("code"), "failure_type": row.get("failure_type"),
            "status": row.get("status"),
            "flags": json.loads(row.get("flags") or "[]") if row.get("flags") else [],
            "description": service.dtc_description(row.get("code")),
        })
    identification: dict[str, dict] = {}
    for row in readings:
        identification.setdefault(row.get("module") or "?", {})[row.get("did")] = {
            "name": row.get("name"), "hex": row.get("value_hex"),
            "ascii": row.get("value_ascii"), "status": row.get("status"),
        }
    seen: set[str] = set()
    for row in module_rows:
        rid = row.get("request_id")
        seen.add(rid)
        dump["modules"].append({
            "bus": row.get("bus"), "request_id": rid, "response_id": row.get("response_id"),
            "kind": row.get("kind"), "dtcs": groups.get(rid, []),
            "identification": identification.get(rid, {}),
        })
    for rid, group in groups.items():
        if rid not in seen:
            dump["modules"].append({"bus": None, "request_id": rid, "response_id": None,
                                    "kind": None, "dtcs": group,
                                    "identification": identification.get(rid, {})})
    dump["generic"]["dtcs"]["stored"] = [
        {"code": item["code"], "description": item.get("description")}
        for item in groups.get("PCM", [])
    ]
    dump["totals"] = {
        "modules": len(dump["modules"]), "dtcs": len(dtcs), "readings": len(readings),
    }
    return dump


# --------------------------------------------------------------------------- #
# registry
# --------------------------------------------------------------------------- #
@dataclass
class StoredReport:
    id: str
    created: str
    source: str
    formats: list[str]
    out_dir: str
    paths: dict[str, str]
    totals: dict
    aborted: str | None
    dump: dict = field(repr=False, default_factory=dict)

    def meta(self) -> dict:
        return {
            "id": self.id, "created": self.created, "source": self.source,
            "formats": self.formats, "out_dir": self.out_dir,
            "paths": self.paths, "totals": self.totals, "aborted": self.aborted,
            "vehicle": self.dump.get("vehicle", {}),
        }


class ReportRegistry:
    """Reports generated this process. Files live under the data dir."""

    def __init__(self, limit: int = 50):
        self._lock = threading.Lock()
        self._reports: dict[str, StoredReport] = {}
        self._order: list[str] = []
        self._limit = limit

    def add(self, dump: dict, formats: list[str], *, source: str) -> StoredReport:
        formats = [fmt.strip().lower() for fmt in formats if fmt and fmt.strip()]
        if not formats:
            raise validation("at least one format is required")
        rid = uuid.uuid4().hex[:12]
        out_dir = data_dir() / "dumps" / f"{_stamp()}-{rid}"
        try:
            paths = report_mod.write_dump(dump, out_dir, formats)
        except ValueError as exc:
            raise validation(str(exc), code="bad_format") from exc
        report = StoredReport(
            id=rid, created=dump.get("generated_at") or _stamp(), source=source,
            formats=formats, out_dir=str(out_dir),
            paths={path.suffix.lstrip("."): str(path) for path in paths},
            totals=dump.get("totals", {}), aborted=dump.get("aborted"), dump=dump,
        )
        with self._lock:
            self._reports[rid] = report
            self._order.append(rid)
            for stale in self._order[:-self._limit]:
                self._reports.pop(stale, None)
            self._order = self._order[-self._limit:]
        return report

    def get(self, report_id: str) -> StoredReport | None:
        with self._lock:
            return self._reports.get(report_id)

    def list(self) -> list[dict]:
        with self._lock:
            return [self._reports[rid].meta() for rid in reversed(self._order)
                    if rid in self._reports]

    def zip_bytes(self, report: StoredReport) -> bytes:
        import io

        buffer = io.BytesIO()
        with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
            for fmt, path in report.paths.items():
                target = Path(path)
                if target.exists():
                    archive.write(target, arcname=f"vehicle.{fmt}")
            archive.writestr("README.txt",
                             "pacifica-obd report export. Generated locally; "
                             "contains only data read from this vehicle.\n")
        return buffer.getvalue()


# --------------------------------------------------------------------------- #
# comparison (structural)
# --------------------------------------------------------------------------- #
def compare_sessions(a: dict, b: dict) -> dict:
    """Structural diff of two dumps: DTCs and identification changes."""
    def dtc_keys(dump: dict) -> set[tuple[str, str, str]]:
        keys = set()
        for module in dump.get("modules", []):
            for dtc in module.get("dtcs", []):
                keys.add((module.get("request_id") or "?", dtc.get("code") or "?",
                          dtc.get("status") or ""))
        for code in dump.get("generic", {}).get("dtcs", {}).get("stored", []):
            keys.add(("PCM", code.get("code") or "?", "stored"))
        return keys

    def ident_map(dump: dict) -> dict[tuple[str, str], str | None]:
        out: dict[tuple[str, str], str | None] = {}
        for module in dump.get("modules", []):
            for did, value in (module.get("identification") or {}).items():
                out[(module.get("request_id") or "?", did)] = (
                    value.get("ascii") or value.get("hex")
                )
        return out

    a_keys, b_keys = dtc_keys(a), dtc_keys(b)
    a_ident, b_ident = ident_map(a), ident_map(b)
    changed = [
        {"module": key[0], "did": key[1], "before": a_ident.get(key), "after": b_ident.get(key)}
        for key in sorted(set(a_ident) & set(b_ident)) if a_ident[key] != b_ident[key]
    ]
    return {
        "a": {"vin": a.get("vehicle", {}).get("vin"), "totals": a.get("totals", {}),
              "generated_at": a.get("generated_at")},
        "b": {"vin": b.get("vehicle", {}).get("vin"), "totals": b.get("totals", {}),
              "generated_at": b.get("generated_at")},
        "dtcs": {
            "appeared": [list(item) for item in sorted(b_keys - a_keys)],
            "cleared": [list(item) for item in sorted(a_keys - b_keys)],
            "unchanged": len(a_keys & b_keys),
        },
        "identification_changed": changed,
        "totals_delta": {
            key: (b.get("totals", {}).get(key, 0) - a.get("totals", {}).get(key, 0))
            for key in set(a.get("totals", {})) | set(b.get("totals", {}))
        },
    }


